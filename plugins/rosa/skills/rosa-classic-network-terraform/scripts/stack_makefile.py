"""Generate a split-stack Makefile (network/ + cluster root) for MOBB ROSA Terraform."""

from __future__ import annotations

from pathlib import Path


def write_split_stack_makefile(
    stack_dir: Path,
    *,
    aws_region: str,
    has_network: bool | None = None,
) -> Path:
    """Write Makefile at stack_dir. has_network auto-detected when None."""
    stack_dir = stack_dir.resolve()
    if has_network is None:
        has_network = (stack_dir / "network" / "main.tf").is_file()

    network_flag = "1" if has_network else "0"
    path = stack_dir / "Makefile"
    body = _template(aws_region=aws_region, network_stack=network_flag)
    path.write_text(body, encoding="utf-8")
    return path


def _template(*, aws_region: str, network_stack: str) -> str:
    return f'''# Generated by MOBB ROSA skills — review before destroy.
# Apply order: network → cluster. Destroy order: cluster → network.

AWS_REGION ?= {aws_region}
export AWS_DEFAULT_REGION := $(AWS_REGION)
# Export RHCS_TOKEN before cluster-plan / cluster-apply (see README: rosa token).

CLUSTER_DIR := .
NETWORK_DIR := network
NETWORK_STACK := {network_stack}

.PHONY: help init fmt validate \\
\tcluster-init cluster-fmt cluster-validate cluster-plan cluster-apply cluster-destroy \\
\tnetwork-init network-fmt network-validate network-plan network-apply network-destroy \\
\tplan apply destroy

help:
\t@echo "Split ROSA stack (cluster root + optional network/)"
\t@echo "  make init      terraform init (cluster + network when present)"
\t@echo "  make plan      network plan then cluster plan (when network/)"
\t@echo "  make apply     network apply then cluster apply"
\t@echo "  make destroy   cluster destroy then network destroy"
\t@echo "  make cluster-plan / network-plan   single-root targets"

init: cluster-init
ifeq ($(NETWORK_STACK),1)
init: network-init
endif

fmt: cluster-fmt
ifeq ($(NETWORK_STACK),1)
fmt: network-fmt
endif

validate: cluster-validate
ifeq ($(NETWORK_STACK),1)
validate: network-validate
endif

cluster-init:
\tcd $(CLUSTER_DIR) && terraform init

cluster-fmt:
\tcd $(CLUSTER_DIR) && terraform fmt -recursive

cluster-validate:
\tcd $(CLUSTER_DIR) && terraform validate

cluster-plan:
\tcd $(CLUSTER_DIR) && terraform plan

cluster-apply:
\tcd $(CLUSTER_DIR) && terraform apply

cluster-destroy:
\tcd $(CLUSTER_DIR) && terraform destroy

ifeq ($(NETWORK_STACK),1)
network-init:
\tcd $(NETWORK_DIR) && terraform init

network-fmt:
\tcd $(NETWORK_DIR) && terraform fmt -recursive

network-validate:
\tcd $(NETWORK_DIR) && terraform validate

network-plan:
\tcd $(NETWORK_DIR) && terraform plan

network-apply:
\tcd $(NETWORK_DIR) && terraform apply

network-destroy:
\tcd $(NETWORK_DIR) && terraform destroy

plan: network-plan cluster-plan

apply: network-apply cluster-apply

destroy: cluster-destroy network-destroy
else
plan: cluster-plan

apply: cluster-apply

destroy: cluster-destroy
endif
'''
